/**
 * Format currency in Tanzanian Shillings (TZS) using integer representation
 */
export function formatTZS(amount: number): string {
  const rounded = Math.round(amount);
  return `TZS ${rounded.toLocaleString('en-US')}`;
}

/**
 * Format view counts with localized Swahili and English suffixes
 */
export function formatViews(views: number, lang: Language): string {
  if (views >= 1000000) {
    const val = (views / 1000000).toFixed(1).replace('.0', '');
    return lang === 'sw' ? `${val}M` : `${val}M`;
  }
  if (views >= 1000) {
    const val = (views / 1000).toFixed(1).replace('.0', '');
    return lang === 'sw' ? `${val}K` : `${val}K`;
  }
  return views.toLocaleString();
}

/**
 * Format relative time in East Africa Time (Africa/Dar_es_Salaam)
 */
export function formatRelativeTime(dateString: string, lang: Language): string {
  const date = new Date(dateString);
  const now = new Date();
  const diffInSeconds = Math.floor((now.getTime() - date.getTime()) / 1000);

  if (diffInSeconds < 60) {
    return lang === 'sw' ? 'sasa hivi' : 'just now';
  }
  const minutes = Math.floor(diffInSeconds / 60);
  if (minutes < 60) {
    return lang === 'sw' ? `dakika ${minutes} zilizopita` : `${minutes} min ago`;
  }
  const hours = Math.floor(minutes / 60);
  if (hours < 24) {
    return lang === 'sw' ? `saa ${hours} zilizopita` : `${hours} hours ago`;
  }
  const days = Math.floor(hours / 24);
  if (days < 30) {
    return lang === 'sw' ? `siku ${days} zilizopita` : `${days} days ago`;
  }
  const months = Math.floor(days / 30);
  if (months < 12) {
    return lang === 'sw' ? `miezi ${months} iliyopita` : `${months} months ago`;
  }
  const years = Math.floor(months / 12);
  return lang === 'sw' ? `miaka ${years} iliyopita` : `${years} years ago`;
}

/**
 * Format video duration (seconds to MM:SS or HH:MM:SS)
 */
export function formatDuration(seconds: number): string {
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);

  const formattedMins = String(mins).padStart(2, '0');
  const formattedSecs = String(secs).padStart(2, '0');

  if (hrs > 0) {
    return `${hrs}:${formattedMins}:${formattedSecs}`;
  }
  return `${mins}:${formattedSecs}`;
}
